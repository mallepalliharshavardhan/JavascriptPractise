// --- a program to print numbers from 1 to 5 -------------


console.log("List of numbers");
for(i = 1 ; i <= 5; i++){
    console.log(i);
}


//---- program to print numbers from 5 to 1 -----------------

console.log("List of numbers in reverse");
for (i = 5 ; i >= 1 ; i--){
    console.log(i);
}

